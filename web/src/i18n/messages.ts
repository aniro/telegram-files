export function translateText(value: string, locale: Locale): string {
  if (value.length === 0) {
    return value;
  }

  const leadingWhitespace = value.match(/^\s*/)?.[0] ?? "";
  const trailingWhitespace = value.match(/\s*$/)?.[0] ?? "";
  const text = value.slice(
    leadingWhitespace.length,
    value.length - trailingWhitespace.length,
  );

  if (text.length === 0) {
    return value;
  }

  if (locale === "en") {
    // Check exact reverse map: Chinese -> English
    const exactEn = enMessages[text];
    if (exactEn) {
      return `${leadingWhitespace}${exactEn}${trailingWhitespace}`;
    }

    // Check dynamic reverse patterns
    for (const [pattern, render] of dynamicReverseMessages) {
      const match = pattern.exec(text);
      if (match) {
        return `${leadingWhitespace}${render(...match.slice(1))}${trailingWhitespace}`;
      }
    }

    return value;
  }

  // locale === "zh-CN"
  const exact = zhCNMessages[text];
  if (exact) {
    return `${leadingWhitespace}${exact}${trailingWhitespace}`;
  }

  for (const [pattern, render] of dynamicMessages) {
    const match = pattern.exec(text);
    if (match) {
      return `${leadingWhitespace}${render(...match.slice(1))}${trailingWhitespace}`;
    }
  }

  return value;
}
